"""Minimal structural boundaries. No SDK/Kit dependencies; real adapters are unimplemented."""
from typing import Protocol
from .actions import Pose


class PoseProvider(Protocol):
    def pose(self) -> Pose: ...
    def pose_sample(self) -> dict: ...  # frame, timestamp, valid, quality/covariance


class Clock(Protocol):
    def control_time(self) -> float: ...  # physics time in sim; monotonic on hardware


class Motion(Protocol):
    def body_velocity(self, vx: float, vy: float, wz: float, valid_until_control_s: float) -> None: ...
    def stop(self) -> None: ...
    def healthy(self) -> bool: ...


class ActionIO(PoseProvider, Clock, Protocol):
    def command(self, vx: float, vy: float, heading: float) -> None: ...
    def stop(self) -> None: ...
    def healthy(self) -> bool: ...
    def cancelled(self) -> bool: ...
    def cancel(self) -> None: ...
    def acquire(self, owner) -> None: ...
    def release(self, owner) -> None: ...
    def command_state(self) -> list[float]: ...
    def command_source(self) -> str: ...
    async def update(self) -> None: ...


class Navigation(Protocol):
    obstacles: list[dict]
    excluded: list[dict]
    def plan(self, start: Pose, gauges: list[dict]) -> list[dict]: ...
    def blockers(self, start, end) -> list[str]: ...
    async def navigate_to(self, io: ActionIO, point: dict, cfg, event=None) -> dict: ...
    def cancel(self, io: ActionIO) -> None: ...


class Camera(Protocol):
    async def capture(self, timeout_s: float): ...  # RGB uint8 and timestamped metadata
    def save(self, path, rgb) -> bool: ...
